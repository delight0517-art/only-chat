'use strict';
const assert = require('node:assert/strict');
const { manageRouterAccount } = require('../src/ui/desktop/accountManagement');
(async () => {
  const accounts = [{ id: 'a', provider: 'chatgpt-plan' }, { id: 'b', provider: 'chatgpt-plan' }, { id: 'ag', provider: 'antigravity-cli' }];
  const adapter = { baseUrl: 'http://127.0.0.1:18880', getChain: async () => ({ accounts }) };
  const calls = [];
  const request = async (url, options) => { calls.push({ url, options }); return Response.json({ ok: true, state: 'never-expose-state' }); };
  assert.deepEqual(await manageRouterAccount(adapter, { action: 'remove', accountId: 'a' }, request), { ok: true, pending: false });
  assert.equal(calls[0].url, 'http://127.0.0.1:18880/api/accounts/a');
  assert.equal(calls[0].options.method, 'DELETE');
  assert.equal(calls[0].options.headers.Origin, adapter.baseUrl);
  await manageRouterAccount(adapter, { action: 'reauth', accountId: 'b' }, request);
  assert.match(calls[1].url, /accounts\/b\/reconnect$/);
  const added = await manageRouterAccount(adapter, { action: 'add-chatgpt' }, request);
  assert.deepEqual(added, { ok: true, pending: true });
  assert.match(JSON.parse(calls[2].options.body).id, /^chatgpt-/);
  await assert.rejects(manageRouterAccount(adapter, { action: 'remove', accountId: 'missing' }, request), /찾을 수 없습니다/);
  await assert.rejects(manageRouterAccount(adapter, { action: 'reauth', accountId: 'ag' }, request), /현재 계정은 유지/);
  await assert.rejects(manageRouterAccount({ ...adapter, baseUrl: 'https://evil.example' }, { action: 'add-chatgpt' }, request), /Invalid/);
  await assert.rejects(manageRouterAccount(adapter, { action: 'remove', accountId: 'b' }, async () => Response.json({ error: { message: 'synthetic failure' } }, { status: 503 })), /synthetic failure/);
  assert.deepEqual(await manageRouterAccount(adapter, { action: 'refresh-antigravity' }, request), { ok: true, pending: false });
  assert.equal(calls[3].url, 'http://127.0.0.1:18880/api/antigravity/refresh');
  assert.equal(JSON.parse(calls[3].options.body).id, 'ag', 'refresh current session rather than create duplicate independent accounts');
  assert.equal(calls.length, 4);
  const fs = require('node:fs');
  const source = fs.readFileSync(require('node:path').join(__dirname, '../src/ui/desktop/app.js'), 'utf8');
  const fragment = source.slice(source.indexOf('function providerAccountRows('), source.indexOf('async function providerAccountAction('));
  const rows = new Function(`${fragment}; return providerAccountRows;`)();
  assert.deepEqual(rows('chatgpt', { accountRouter: { accounts } }).map(a => a.id), ['a', 'b']);
  assert.deepEqual(rows('google', { accountRouter: { accounts } }).map(a => a.id), ['ag']);
  assert.deepEqual(rows('chatgpt', { tiers: [{ id: 'fake', provider: 'codex' }] }), [], 'presets are never displayed as logged-in accounts');
  const os = require('node:os');
  const path = require('node:path');
  const { DesktopServer } = require('../src/ui/desktop/server');
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'onlychat-account-isolation-'));
  let server;
  try {
    server = new DesktopServer({ isolated: true, port: 0, dataDir: root, enableQuotaRefresh: false });
    await server.start();
    const origin = `http://127.0.0.1:${server.port}`;
    const response = await fetch(`${origin}/api/account-router/account`, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'add-chatgpt' }) });
    assert.equal(response.status, 503, 'isolated tests cannot launch login or mutate real accounts');
    const blocked = await fetch(`${origin}/api/account-router/account`, { method: 'POST', headers: { Origin: 'https://untrusted.example', 'Content-Type': 'application/json' }, body: '{}' });
    assert.equal(blocked.status, 403, 'cross-origin account mutation is rejected');
  } finally {
    await server?.stop();
    fs.rmSync(root, { recursive: true, force: true });
  }
  console.log('accountManagement: exact-account deletion, reconnect, unique OAuth add, error propagation and real-account rows passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
